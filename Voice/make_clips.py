"""Generate the DRIFTS voice clips from phrases.json with Piper (offline TTS).

    pip install piper-tts                    # once, on a laptop (not needed on the Pi Zero)
    python -m piper.download_voices en_US-libritts_r-medium
    python Voice/make_clips.py [--voice-dir DIR]

Writes:
  Voice/clips/NN_NAME.wav            Tokyo (Pi 5) plays these with aplay
  Voice/sd_card/mp3/NNNN.mp3         copy the mp3 folder to the DFPlayer's microSD (needs ffmpeg)
  Esp32/drifts_esp32/voice_clips.h   clip ids and lengths for the ESP32 firmware

The clip number is the same everywhere, so "SAY:4" plays the Level 2 warning on
the ESP32 and Tokyo alike. Never renumber a phrase; add new ones at the end.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import wave
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
HEADER = REPO / "Esp32" / "drifts_esp32" / "voice_clips.h"


def wav_ms(path: Path) -> int:
    with wave.open(str(path), "rb") as w:
        return round(1000 * w.getnframes() / w.getframerate())


def write_header(phrases: list, lengths: dict) -> str:
    lines = [
        "#pragma once",
        "",
        "// GENERATED by Voice/make_clips.py from Voice/phrases.json. Do not edit:",
        "// change the phrases there and run the script again.",
        "//",
        "// Clip n is /mp3/000n.mp3 on the DFPlayer's microSD card. The same numbers",
        "// are used by Tokyo (Pi 5), so SAY:<n> means the same phrase on both.",
        "",
        "#include <stdint.h>",
        "",
        "enum VoiceClip : uint8_t {",
        "    VOICE_NONE = 0,",
    ]
    for p in phrases:
        lines.append(f"    VOICE_{p['name']} = {p['id']},")
    lines += ["};", "", f"constexpr uint8_t VOICE_CLIP_MAX = {max(p['id'] for p in phrases)};", "",
              "// Clip length in ms (index = clip id), used to hold the buzzer while it plays.",
              "constexpr uint16_t VOICE_CLIP_MS[VOICE_CLIP_MAX + 1] = {"]
    by_id = {p["id"]: p for p in phrases}
    for i in range(0, max(by_id) + 1):
        if i in by_id:
            lines.append(f"    {lengths[i]},   // {i} {by_id[i]['name']}: \"{by_id[i]['text']}\"")
        else:
            lines.append(f"    0,")
    lines += ["};", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--voice-dir", default=".", help="folder holding the downloaded .onnx voice")
    args = ap.parse_args(argv)

    cfg = json.loads((HERE / "phrases.json").read_text())
    v, phrases = cfg["voice"], cfg["phrases"]
    ids = [p["id"] for p in phrases]
    if len(set(ids)) != len(ids) or min(ids) < 1 or max(ids) > 255:
        sys.exit("phrase ids must be unique, 1-255")

    from piper import PiperVoice, SynthesisConfig
    model = Path(args.voice_dir) / f"{v['model']}.onnx"
    voice = PiperVoice.load(str(model))
    syn = SynthesisConfig(speaker_id=v.get("speaker"), length_scale=v.get("length_scale", 1.0))

    clips, mp3 = HERE / "clips", HERE / "sd_card" / "mp3"
    clips.mkdir(exist_ok=True)
    mp3.mkdir(parents=True, exist_ok=True)
    for old in list(clips.glob("*.wav")) + list(mp3.glob("*.mp3")):
        old.unlink()
    ffmpeg = shutil.which("ffmpeg")
    lengths = {}
    for p in phrases:
        out = clips / f"{p['id']:02d}_{p['name']}.wav"
        with wave.open(str(out), "wb") as wf:
            voice.synthesize_wav(p["text"], wf, syn_config=syn)
        lengths[p["id"]] = wav_ms(out)
        if ffmpeg:
            # Short silence in front: the DFPlayer's amplifier clips the first ~100 ms.
            subprocess.run([ffmpeg, "-loglevel", "error", "-y", "-i", str(out),
                            "-af", "adelay=150,loudnorm=I=-14:TP=-1.0", "-ar", "22050", "-ac", "1",
                            "-b:a", "64k", str(mp3 / f"{p['id']:04d}.mp3")], check=True)
            lengths[p["id"]] += 150
        print(f"  {p['id']:2d} {p['name']:<12} {lengths[p['id']]:5d} ms  {p['text']}")
    if not ffmpeg:
        print("ffmpeg not found: WAV clips written, DFPlayer MP3s skipped")
    HEADER.write_text(write_header(phrases, lengths))
    print(f"wrote {clips.relative_to(REPO)}/, {mp3.relative_to(REPO)}/, {HEADER.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
